#!/usr/bin/env python3
"""Regenerates docs/parse_trees.md and docs/evaluation_results.md from the live code."""
import os
import sys

from sqli import scan, blacklist_scan
from sqli.evaluate import evaluate, summarize, load_queries
from sqli.tree import render_ascii, to_mermaid

ROOT = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(ROOT, "docs")

NORMAL = "SELECT * FROM users WHERE id = '5'"
INJECTED = "SELECT * FROM users WHERE id = '' OR '1'='1'"
INJECTED2 = "SELECT * FROM users WHERE id = '' OR 1=1--"


def parse_trees():
    out = ["# Parse trees: normal vs injected query", "",
           "Generated by `generate_docs.py` from the real parser (use these as the reference for the hand-drawn draw.io trees).", ""]
    for title, q in (("Query 1 - normal", NORMAL), ("Query 2 - injected (tautology)", INJECTED),
                     ("Query 3 - injected (OR + comment)", INJECTED2)):
        res = scan(q)
        out += [f"## {title}", "", f"`{q}`", "", f"**Verdict:** {res.verdict}  ", f"**Why:** {res.explanation}", "",
                "```", render_ascii(res.tree), "```", "",
                "Mermaid source (paste into draw.io: Arrange > Insert > Advanced > Mermaid):", "",
                "```mermaid", to_mermaid(res.tree), "```", ""]
    out += ["## Key structural difference", "",
            "| | Normal | Injected |", "|---|---|---|",
            "| WHERE child | `Comparison` (single condition) | `Or` with **two** branches |",
            "| Number of conditions | 1 | 2 (second one is `'1'='1'`, a tautology) |",
            "| Meaning | rows where id = 5 | **every row** (OR with always-true) |", ""]
    return "\n".join(out)


def evaluation():
    rows = evaluate()
    s = summarize(rows)
    out = ["# Evaluation: grammar scanner vs keyword blacklist", "",
           "Generated by `generate_docs.py` (10 normal + 10 injected queries from `data/`).", "",
           "| # | Truth | Grammar scanner | Keyword blacklist | Query |", "|---|---|---|---|---|"]
    for i, (q, truth, g, b) in enumerate(rows, 1):
        def cell(flag):
            return ("detected" if flag else "**MISSED**") if truth else ("**false positive**" if flag else "ok")
        out.append(f"| {i} | {'injected' if truth else 'normal'} | {cell(g)} | {cell(b)} | `{q}` |")
    out += ["", "## Summary", "",
            "| | Injections detected | False positives |", "|---|---|---|",
            f"| Grammar scanner | {s['grammar_detected']}/{s['injected']} | {s['grammar_false_positives']}/{s['normal']} |",
            f"| Keyword blacklist | {s['blacklist_detected']}/{s['injected']} | {s['blacklist_false_positives']}/{s['normal']} |", "",
            "## Injections that bypass the blacklist", ""]
    for q in load_queries("bypass_queries.txt"):
        res = scan(q)
        out += [f"- `{q}`  ", f"  blacklist: passed  |  grammar: **{res.verdict}** - {res.explanation}"]
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    os.makedirs(DOCS, exist_ok=True)
    for name, text in (("parse_trees.md", parse_trees()), ("evaluation_results.md", evaluation())):
        with open(os.path.join(DOCS, name), "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote docs/" + name)
